using System.Collections.Generic;

namespace Ozikol_BCC.Infrastructure.Services.Email;

/// <summary>
/// Comprehensive configuration, mailbox allocation, and DNS health report for a custom domain's email suite.
/// </summary>
public sealed class DomainEmailConfigDto
{
    /// <summary>
    /// Gets or sets the custom domain name (e.g. "nightpresssecurity.co.uk").
    /// </summary>
    public string Domain { get; set; } = string.Empty;

    /// <summary>
    /// Gets or sets a value indicating whether the domain is registered on the mail server.
    /// </summary>
    public bool DomainExistsInMailserver { get; set; }

    /// <summary>
    /// Gets or sets the 2048-bit DKIM public key string generated by Mailcow for this domain.
    /// </summary>
    public string DkimPublicKey { get; set; } = string.Empty;

    /// <summary>
    /// Gets or sets all active mailboxes currently created on this domain.
    /// </summary>
    public List<DomainMailboxDto> Mailboxes { get; set; } = new();

    /// <summary>
    /// Gets or sets maximum free custom mailboxes permitted for the workspace (default: 1 free).
    /// </summary>
    public int MaxFreeMailboxes { get; set; } = 1;

    /// <summary>
    /// Gets or sets the current count of user-created custom mailboxes (excluding the automated "noreply" mailbox).
    /// </summary>
    public int CurrentCustomMailboxCount { get; set; }

    /// <summary>
    /// Gets the count of active custom mailboxes used. Alias for <see cref="CurrentCustomMailboxCount"/>.
    /// </summary>
    public int CustomMailboxesUsed => CurrentCustomMailboxCount;

    /// <summary>
    /// Gets the maximum allowed free custom mailboxes. Alias for <see cref="MaxFreeMailboxes"/>.
    /// </summary>
    public int CustomMailboxesAllowed => MaxFreeMailboxes;

    /// <summary>
    /// Gets a value indicating whether the tenant can create another free mailbox.
    /// </summary>
    public bool CanCreateMoreMailboxes => CurrentCustomMailboxCount < MaxFreeMailboxes;

    /// <summary>
    /// Gets or sets the 4 required DNS records (MX, SPF, DKIM, DMARC) with real-time verification status.
    /// </summary>
    public List<EmailDnsRecordDto> DnsRecords { get; set; } = new();

    /// <summary>
    /// Gets or sets a value indicating whether the MX record is properly pointed to mail.ozikol.cloud.
    /// </summary>
    public bool IsMxVerified { get; set; }

    /// <summary>
    /// Gets or sets a value indicating whether the SPF TXT record is properly configured.
    /// </summary>
    public bool IsSpfVerified { get; set; }

    /// <summary>
    /// Gets or sets a value indicating whether the DKIM TXT record matches the public key.
    /// </summary>
    public bool IsDkimVerified { get; set; }

    /// <summary>
    /// Gets or sets a value indicating whether the DMARC TXT record is present.
    /// </summary>
    public bool IsDmarcVerified { get; set; }

    /// <summary>
    /// Gets a value indicating whether all 4 email DNS records are verified and operational.
    /// </summary>
    public bool IsAllEmailDnsVerified => IsMxVerified && IsSpfVerified && IsDkimVerified && IsDmarcVerified;
}

