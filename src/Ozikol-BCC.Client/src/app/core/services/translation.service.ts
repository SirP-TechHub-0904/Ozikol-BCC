  public translate(key: string, fallback?: string): string {
    const lang = this.currentLangSubject.value;
    if (COMMITTEES_TRANSLATIONS[lang]?.[key]) {
      return COMMITTEES_TRANSLATIONS[lang][key];
    }
    if (TranslationService.BILLING_BANNER_TRANSLATIONS[lang]?.[key]) {
      return TranslationService.BILLING_BANNER_TRANSLATIONS[lang][key];
    }
    const table = this.translations[lang] || this.translations['en'];
    if (table && table[key]) {
      return table[key];
    }
    // Fallback to English dictionary
    if (COMMITTEES_TRANSLATIONS['en']?.[key]) {
      return COMMITTEES_TRANSLATIONS['en'][key];
    }
    if (this.translations['en'] && this.translations['en'][key]) {
      return this.translations['en'][key];
    }
    if (TranslationService.BILLING_BANNER_TRANSLATIONS['en']?.[key]) {
      return TranslationService.BILLING_BANNER_TRANSLATIONS['en'][key];
    }
    return fallback ?? key;
  }

  private getInitialLanguage(): SupportedLanguage {
    try {
      const saved = localStorage.getItem(this.STORAGE_KEY) as SupportedLanguage;
      if (saved && SUPPORTED_LANGUAGES.some(l => l.code === saved)) {
        return saved;
      }
      const navLang = navigator.language?.split('-')[0]?.toLowerCase() as SupportedLanguage;
      if (navLang && SUPPORTED_LANGUAGES.some(l => l.code === navLang)) {
        return navLang;
      }
    } catch {}
    return 'en';
  }
